-- Newsletter subscribers
-- Run once in Supabase: Dashboard -> SQL Editor -> New query -> paste -> Run.
-- Safe to run again (everything is idempotent).
--
-- The footer subscribe form writes here with the public anon key. Visitors can
-- only insert; reading and deleting the list is limited to the admin panel.

create table if not exists public.newsletter_subscribers (
  id         bigint generated by default as identity primary key,
  email      text not null,
  source     text not null default 'footer',
  created_at timestamptz not null default now()
);

-- One row per email address, case-insensitive.
create unique index if not exists newsletter_subscribers_email_key
  on public.newsletter_subscribers (lower(email));

alter table public.newsletter_subscribers enable row level security;

drop policy if exists "newsletter_public_insert" on public.newsletter_subscribers;
create policy "newsletter_public_insert" on public.newsletter_subscribers
  for insert
  with check (
    email is not null
    and length(trim(email)) between 5 and 254
    and position('@' in email) > 1
  );

drop policy if exists "newsletter_admin_read" on public.newsletter_subscribers;
create policy "newsletter_admin_read" on public.newsletter_subscribers
  for select
  using (public.is_admin());

drop policy if exists "newsletter_admin_delete" on public.newsletter_subscribers;
create policy "newsletter_admin_delete" on public.newsletter_subscribers
  for delete
  using (public.is_admin());
